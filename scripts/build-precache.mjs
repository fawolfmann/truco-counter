// Regenerates app/precache.js: the service worker's file list and a version hash of their contents.
// Run after any change under app/. With --check it only verifies the file is current (used by CI).
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const APP_DIR = fileURLToPath(new URL("../app/", import.meta.url));
const OUTPUT = join(APP_DIR, "precache.js");
const SKIP = new Set(["precache.js", "sw.js", "_headers", "robots.txt", ".DS_Store"]);

function listFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return listFiles(full);
    return SKIP.has(entry.name) ? [] : [relative(APP_DIR, full).split(sep).join("/")];
  });
}

export function buildPrecache() {
  const files = listFiles(APP_DIR).sort();
  const hash = createHash("sha256");
  for (const file of files) hash.update(file).update("\0").update(readFileSync(join(APP_DIR, file)));
  const version = hash.digest("hex").slice(0, 12);
  const list = ["./", ...files].map((f) => `  ${JSON.stringify(f)},`).join("\n");
  return `// Generated by scripts/build-precache.mjs. Do not edit.\nself.APP_VERSION = "${version}";\nself.PRECACHE = [\n${list}\n];\n`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const next = buildPrecache();
  let current = "";
  try { current = readFileSync(OUTPUT, "utf8"); } catch { /* first run */ }
  if (process.argv.includes("--check")) {
    if (current !== next) {
      process.stderr.write("app/precache.js is out of date. Run `npm run build` and commit the result.\n");
      process.exit(1);
    }
  } else if (current !== next) {
    writeFileSync(OUTPUT, next);
    process.stdout.write("app/precache.js updated\n");
  }
}
